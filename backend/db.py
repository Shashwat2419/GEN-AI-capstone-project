"""Trip persistence.

* If SUPABASE_URL and SUPABASE_SERVICE_KEY are set, trips are stored in Supabase
  PostgreSQL (tables: trips, trip_days, activities - see supabase/schema.sql)
  through the PostgREST HTTP API, so no extra SDK is needed.
* Otherwise a local SQLite file is used, so the API still works in development.

Every trip belongs to an anonymous ``client_id`` (generated by the browser), so
visitors only ever see their own trips.
"""
import json
import os
import sqlite3
from datetime import datetime, timezone
from typing import Dict, List, Optional

import requests

SUPABASE_URL = os.environ.get("SUPABASE_URL", "").strip().rstrip("/")
if SUPABASE_URL.endswith("/rest/v1"):
    SUPABASE_URL = SUPABASE_URL[: -len("/rest/v1")]
SUPABASE_KEY = os.environ.get("SUPABASE_SERVICE_KEY", "")
SQLITE_PATH = os.environ.get(
    "SQLITE_PATH", os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "trips.db"))


class StorageError(Exception):
    pass


class NotFound(StorageError):
    pass


def backend_name() -> str:
    return "supabase" if (SUPABASE_URL and SUPABASE_KEY) else "sqlite"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _summary_cols(itin: Dict) -> Dict:
    p = itin.get("prefs", {})
    return {
        "destination": itin["destination"], "country": itin.get("country") or None,
        "currency": itin.get("currency") or None, "num_days": len(itin["days"]),
        "budget_level": p.get("budget"), "party": p.get("party"), "pace": p.get("pace"),
        "start_date": p.get("start_date") or None,
    }


# --------------------------------------------------------------------------- #
# Supabase (PostgREST)
# --------------------------------------------------------------------------- #
def _sb(method: str, path: str, params: Optional[Dict] = None, body=None, returning: bool = True):
    headers = {"apikey": SUPABASE_KEY, "Authorization": "Bearer " + SUPABASE_KEY,
               "Content-Type": "application/json",
               "Prefer": "return=representation" if returning else "return=minimal"}
    try:
        resp = requests.request(method, SUPABASE_URL + "/rest/v1/" + path, headers=headers,
                                params=params, data=json.dumps(body) if body is not None else None,
                                timeout=20)
    except requests.exceptions.RequestException as exc:
        raise StorageError("Could not reach Supabase: %s" % exc)
    if resp.status_code >= 300:
        try:
            msg = resp.json().get("message", resp.text)
        except ValueError:
            msg = resp.text
        raise StorageError("Supabase error (%s): %s" % (resp.status_code, str(msg)[:300]))
    if not returning or not resp.text:
        return None
    return resp.json()


def _sb_write_children(trip_id: str, itin: Dict) -> None:
    days_rows = [{"trip_id": trip_id, "day_number": d["day"], "day_date": d.get("date"),
                  "theme": d.get("theme")} for d in itin["days"]]
    created = _sb("POST", "trip_days", body=days_rows) or []
    id_by_day = {r["day_number"]: r["id"] for r in created}
    acts = []
    for d in itin["days"]:
        pos = 0
        for slot in d["slots"]:
            for it in slot["items"]:
                acts.append({"trip_day_id": id_by_day[d["day"]], "slot": slot["slot"], "position": pos,
                             "name": it["name"], "area": it.get("area"), "lat": it["lat"], "lon": it["lon"],
                             "description": it.get("description"), "cost_local": it["cost_local"],
                             "duration_hrs": it["duration_hrs"], "tags": it.get("tags", [])})
                pos += 1
    if acts:
        _sb("POST", "activities", body=acts, returning=False)


def _sb_save(client_id: str, name: str, itin: Dict, trip_id: Optional[str]) -> str:
    row = dict(_summary_cols(itin), name=name, payload=itin, updated_at=_now())
    if trip_id:
        updated = _sb("PATCH", "trips", params={"id": "eq." + trip_id, "client_id": "eq." + client_id}, body=row)
        if updated:
            _sb("DELETE", "trip_days", params={"trip_id": "eq." + trip_id}, returning=False)
            _sb_write_children(trip_id, itin)
            return trip_id
    row["client_id"] = client_id
    created = _sb("POST", "trips", body=row)
    new_id = created[0]["id"]
    _sb_write_children(new_id, itin)
    return new_id


# --------------------------------------------------------------------------- #
# SQLite fallback
# --------------------------------------------------------------------------- #
def _lite() -> sqlite3.Connection:
    try:
        os.makedirs(os.path.dirname(SQLITE_PATH), exist_ok=True)
        conn = sqlite3.connect(SQLITE_PATH)
        conn.row_factory = sqlite3.Row
        conn.execute("""CREATE TABLE IF NOT EXISTS trips (
            id INTEGER PRIMARY KEY AUTOINCREMENT, client_id TEXT NOT NULL, name TEXT NOT NULL,
            destination TEXT NOT NULL, num_days INTEGER NOT NULL, created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL, payload TEXT NOT NULL)""")
        return conn
    except (OSError, sqlite3.Error) as exc:
        raise StorageError("Could not open the local database: %s" % exc)


def _lite_save(client_id: str, name: str, itin: Dict, trip_id: Optional[str]) -> str:
    payload, now = json.dumps(itin), _now()
    try:
        with _lite() as conn:
            if trip_id:
                cur = conn.execute(
                    "UPDATE trips SET name=?, destination=?, num_days=?, updated_at=?, payload=? "
                    "WHERE id=? AND client_id=?",
                    (name, itin["destination"], len(itin["days"]), now, payload, int(trip_id), client_id))
                if cur.rowcount:
                    return str(trip_id)
            cur = conn.execute(
                "INSERT INTO trips (client_id, name, destination, num_days, created_at, updated_at, payload) "
                "VALUES (?,?,?,?,?,?,?)",
                (client_id, name, itin["destination"], len(itin["days"]), now, now, payload))
            return str(cur.lastrowid)
    except (sqlite3.Error, ValueError) as exc:
        raise StorageError("Could not save the trip: %s" % exc)


# --------------------------------------------------------------------------- #
# Public API
# --------------------------------------------------------------------------- #
def save_trip(client_id: str, name: str, itin: Dict, trip_id: Optional[str] = None) -> str:
    if backend_name() == "supabase":
        return _sb_save(client_id, name, itin, trip_id)
    return _lite_save(client_id, name, itin, trip_id)


def list_trips(client_id: str) -> List[Dict]:
    if backend_name() == "supabase":
        rows = _sb("GET", "trips", params={
            "client_id": "eq." + client_id, "order": "updated_at.desc",
            "select": "id,name,destination,num_days,created_at,updated_at"})
        return rows or []
    try:
        with _lite() as conn:
            rows = conn.execute(
                "SELECT id, name, destination, num_days, created_at, updated_at FROM trips "
                "WHERE client_id=? ORDER BY updated_at DESC", (client_id,)).fetchall()
        return [dict(r, id=str(r["id"])) for r in rows]
    except sqlite3.Error as exc:
        raise StorageError("Could not read trips: %s" % exc)


def load_trip(client_id: str, trip_id: str) -> Dict:
    if backend_name() == "supabase":
        rows = _sb("GET", "trips", params={"id": "eq." + trip_id, "client_id": "eq." + client_id,
                                           "select": "payload"})
        if not rows:
            raise NotFound("That trip was not found.")
        return rows[0]["payload"]
    try:
        with _lite() as conn:
            row = conn.execute("SELECT payload FROM trips WHERE id=? AND client_id=?",
                               (int(trip_id), client_id)).fetchone()
    except (sqlite3.Error, ValueError) as exc:
        raise StorageError("Could not load the trip: %s" % exc)
    if row is None:
        raise NotFound("That trip was not found.")
    return json.loads(row["payload"])


def delete_trip(client_id: str, trip_id: str) -> None:
    if backend_name() == "supabase":
        _sb("DELETE", "trips", params={"id": "eq." + trip_id, "client_id": "eq." + client_id}, returning=False)
        return
    try:
        with _lite() as conn:
            conn.execute("DELETE FROM trips WHERE id=? AND client_id=?", (int(trip_id), client_id))
    except (sqlite3.Error, ValueError) as exc:
        raise StorageError("Could not delete the trip: %s" % exc)
